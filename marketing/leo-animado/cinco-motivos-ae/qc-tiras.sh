# Tiras de conferência quadro a quadro das trocas (uma imagem por grupo de quadros). Uso: bash qc-tiras.sh <vídeo> <pasta>
set -eu
V="$1"; D="$2"; mkdir -p "$D"
tira() { # nome, lista de quadros separada por espaço
  local nome="$1"; shift; local sel=""; for q in "$@"; do sel="$sel+eq(n\,$q)"; done; sel="${sel#+}"
  ffmpeg -v error -y -i "$V" -vf "select='$sel',scale=216:-1,tile=8x$(( ($# + 7) / 8 )):padding=3:color=white" -frames:v 1 "$D/$nome.jpg"
}
